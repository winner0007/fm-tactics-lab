"""Keep the isolated host's PI validation in sync with the editor catalog."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
source = (root / 'Sources/TacticsCore/NativeCatalog.swift').read_text()
positions = dict(re.findall(r'\.init\(id:"(\w+)",label:"[^"]+",mask:(\d+)', source))
roles = dict(re.findall(r'\.init\(id:"(\w+)",label:"[^"]+",phase:\.\w+,flags:(\d+)', source))
rows = re.findall(r'^\s+([01]):(\w+):(\w+)=([0-3]{43})$', source, re.M)
assert len(rows) == 221
text = '// Generated by scripts/sync-native-policy.py from NativeCatalog.swift.\n'
text += 'struct NativePIPolicy { unsigned phase,position; uint64_t role; const char *states; };\n'
text += 'static const NativePIPolicy nativePIPolicies[]={\n'
text += ''.join(f'  {{{phase},{positions[position]},{roles[role]}ULL,"{states}"}},\n' for phase, position, role, states in rows)
text += '};\n'
(root / 'native/EnginePlayerPolicy.h').write_text(text)
